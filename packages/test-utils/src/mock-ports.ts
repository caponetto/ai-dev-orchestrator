export function createArtifactRef(type: ArtifactType, version = 1): ArtifactRef {
  return { type, name: type, version, checksum: 'abc' };
}

export type TrackingArtifactStore = ArtifactStore & {
  stored: Map<string, { version: number; content: string }>;
};

export function createMockArtifactStore(): TrackingArtifactStore {
  const stored = new Map<string, { version: number; content: string }>();

  return {
    stored,
    store: vi.fn(
      (input: { type: ArtifactType; name: string; content: string; producedBy: string }) => {
        const existing = stored.get(input.type);
        const version = existing ? existing.version + 1 : 1;
        stored.set(input.type, { version, content: input.content });
        return Promise.resolve(createArtifactRef(input.type, version));
      },
    ),
    getLatest: vi.fn((type: ArtifactType) => {
      const entry = stored.get(type);
      if (!entry) {
        return Promise.resolve(null);
      }
      return Promise.resolve({
        ref: createArtifactRef(type, entry.version),
        type,
        name: type,
        version: entry.version,
        content: entry.content,
        checksum: 'abc',
        producedBy: 'test',
        createdAt: new Date().toISOString(),
        sizeBytes: entry.content.length,
      });
    }),
    get: vi.fn((ref: ArtifactRef) => {
      const entry = stored.get(ref.type);
      if (!entry) {
        return Promise.resolve(null as never);
      }
      return Promise.resolve({
        ref: createArtifactRef(ref.type, entry.version),
        type: ref.type,
        name: ref.type,
        version: entry.version,
        content: entry.content,
        checksum: 'abc',
        producedBy: 'test',
        createdAt: new Date().toISOString(),
        sizeBytes: entry.content.length,
      });
    }),
    list: vi.fn((query: { type?: ArtifactType }) => {
      if (query.type) {
        const entry = stored.get(query.type);
        if (!entry) {
          return Promise.resolve([]);
        }
        return Promise.resolve([createArtifactRef(query.type, entry.version)]);
      }
      return Promise.resolve([]);
    }),
    history: vi.fn(() => Promise.resolve([])),
    verify: vi.fn(() =>
      Promise.resolve({
        valid: true,
        expectedChecksum: 'abc',
        actualChecksum: 'abc',
        ref: createArtifactRef('plan'),
      }),
    ),
    inventory: vi.fn(() =>
      Promise.resolve({ runId: '', artifacts: [], totalCount: 0, totalSizeBytes: 0 }),
    ),
  };
}

