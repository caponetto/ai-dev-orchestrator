function defaultContentForArtifact(artifactType: string, role: string): string {
  if (artifactType.endsWith('_review')) {
    return '---\napproved: true\nfindings: []\n---\nLooks good.';
  }
  if (artifactType === 'plan') {
    return JSON.stringify({
      summary: 'Fixture plan',
      tasks: [{ taskId: 'task-1', description: 'Fixture task', files: [], dependencies: [] }],
    });
  }
  if (artifactType === 'verification') {
    return JSON.stringify({ passed: true, failures: [] });
  }
  return `Generated by ${role}`;
}

export interface MockRunnerOptions {
  artifactStore?: ArtifactStore;
  roleToArtifactType?: Record<string, ArtifactType>;
}

export function createMockRunnerSystem(options: MockRunnerOptions = {}): RunnerSystem {
  const roleMap: Record<string, ArtifactType | undefined> = {
    ...DEFAULT_ROLE_TO_ARTIFACT,
    ...options.roleToArtifactType,
  };

  async function handleDispatch(request: {
    role: string;
    runId: string;
    stateId: string;
  }): Promise<DispatchResult> {
    const artifactType = roleMap[request.role] ?? (request.role as ArtifactType);
    const ref = createArtifactRef(artifactType);
    const content = defaultContentForArtifact(artifactType, request.role);

    if (options.artifactStore) {
      await options.artifactStore.store({
        type: artifactType,
        name: artifactType,
        content,
        producedBy: request.role,
      });
    }

    return {
      workerId: `w-${request.role}`,
      status: 'success' as const,
      role: request.role as RoleId,
      outputArtifacts: [ref],
      metrics: {
        startedAt: new Date().toISOString(),
        completedAt: new Date().toISOString(),
        durationMs: 10,
        inputTokens: 100,
        outputTokens: 50,
        retryCount: 0,
        modelUsed: 'fixture-model',
      },
    };
  }

  return {
    dispatch: vi.fn(handleDispatch),
    dispatchParallel: vi.fn(
      async (requests: readonly { role: string; runId: string; stateId: string }[]) => {
        const results: DispatchResult[] = [];
        for (const request of requests) {
          results.push(await handleDispatch(request));
        }
        return results;
      },
    ),
    getWorkerStatus: vi.fn().mockReturnValue(null),
    cancelWorker: vi.fn(),
    cancelAllWorkers: vi.fn().mockResolvedValue(undefined),
    setWorkerCounter: vi.fn(),
  };
}

