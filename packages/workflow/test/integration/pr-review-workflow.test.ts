const PR_REVIEW_ROLE_TO_ARTIFACT: Record<string, ArtifactType> = {
  setup_worker: 'intake_requirements',
  context_analyst: 'canonical_specification',
  diff_worker: 'codebase_context',
  static_reviewer: 'static_review',
  design_reviewer: 'design_review',
  security_reviewer: 'security_review',
  performance_reviewer: 'performance_review',
  adversarial_reviewer: 'adversarial_review',
  docs_reviewer: 'docs_review',
  ux_reviewer: 'ux_review',
  report_synthesizer: 'review_report',
  review_findings_writer: 'review_findings',
  publish_worker: 'release_summary',
  cleanup_worker: 'release_summary',
};

function prReviewContent(artifactType: string, role: string): string {
  if (artifactType.endsWith('_review')) {
    return '---\napproved: true\nfindings: []\n---\nLooks good.';
  }
  if (artifactType === 'review_report') {
    return JSON.stringify({ summary: 'No critical issues found', findings: [] });
  }
  if (artifactType === 'review_findings') {
    return JSON.stringify({ findings: [], summary: 'Clean PR' });
  }
  return `Generated by ${role}`;
}

function createPrReviewRunner(artifactStore: TrackingArtifactStore): RunnerSystem {
  async function handleDispatch(request: {
    role: string;
    runId: string;
    stateId: string;
  }): Promise<DispatchResult> {
    const artifactType = PR_REVIEW_ROLE_TO_ARTIFACT[request.role] ?? (request.role as ArtifactType);
    const content = prReviewContent(artifactType, request.role);

    await artifactStore.store({
      type: artifactType,
      name: artifactType,
      content,
      producedBy: request.role,
    });

    return {
      workerId: `w-${request.role}`,
      status: 'success' as const,
      role: request.role as RoleId,
      outputArtifacts: [{ type: artifactType, name: artifactType, version: 1, checksum: 'abc' }],
      metrics: {
        startedAt: new Date().toISOString(),
        completedAt: new Date().toISOString(),
        durationMs: 10,
        inputTokens: 100,
        outputTokens: 50,
        retryCount: 0,
        modelUsed: 'fixture-model',
      },
    };
  }

  return {
    dispatch: vi.fn(handleDispatch),
    dispatchParallel: vi.fn(
      async (requests: readonly { role: string; runId: string; stateId: string }[]) => {
        const results: DispatchResult[] = [];
        for (const req of requests) {
          results.push(await handleDispatch(req));
        }
        return results;
      },
    ),
    getWorkerStatus: vi.fn().mockReturnValue(null),
    cancelWorker: vi.fn(),
    cancelAllWorkers: vi.fn().mockResolvedValue(undefined),
    setWorkerCounter: vi.fn(),
  };
}

