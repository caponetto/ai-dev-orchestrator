const TEST_DIR = join(tmpdir(), `pr-review-integration-${String(Date.now())}`);

let journalPath: string;

beforeEach(() => {
  mkdirSync(TEST_DIR, { recursive: true });
  journalPath = join(TEST_DIR, 'journal.md');
});

afterEach(() => {
  rmSync(TEST_DIR, { recursive: true, force: true });
});

describe('PR Review Workflow Integration', () => {
  it('happy path: SETUP → DONE produces expected artifacts', async () => {
    const artifactStore = createMockArtifactStore();
    const runner = createPrReviewRunner(artifactStore);
    const governance = createMockGovernance();
    const contractRegistry = new DefaultIterationContractRegistry();
    const journalWriter = new DefaultJournalWriter(journalPath, 'run-pr-001');
    const statePersistence = createMockStatePersistence();
    const manifestProducer = createMockManifestProducer();

    const controller = new LifecycleController({
      runner,
      artifactStore,
      governanceEngine: governance,
      contractRegistry,
      journalWriter,
      statePersistence,
      manifestProducer,
    });

    const config = {
      runId: 'run-pr-001',
      workflowDefinition: TEST_PR_REVIEW_WORKFLOW,
      governancePolicy: {},
      roleAssignments: {},
      sources: ['https://github.com/org/repo/pull/42'],
    };

    let result = await controller.start(config);

    let iterations = 0;
    while (
      result.finalState !== 'DONE' &&
      result.finalState !== 'FAILED' &&
      result.finalState !== 'ABORTED' &&
      iterations < 15
    ) {
      result = await controller.resume({ type: 'approval', content: 'Approved' });
      iterations++;
    }

    expect(result.finalState).toBe('DONE');

    expect(artifactStore.stored.has('canonical_specification')).toBe(true);
    expect(artifactStore.stored.has('review_report')).toBe(true);
    expect(artifactStore.stored.has('review_findings')).toBe(true);
    expect(artifactStore.stored.has('static_review')).toBe(true);
    expect(artifactStore.stored.has('security_review')).toBe(true);

    // eslint-disable-next-line @typescript-eslint/unbound-method
    expect(runner.dispatchParallel).toHaveBeenCalled();

    const reader = new DefaultJournalReader(journalPath);
    const events = reader.readAll();
    expect(events.some((e) => e.type === 'run_started')).toBe(true);
    expect(events.some((e) => e.type === 'run_completed')).toBe(true);

    const transitions = events.filter((e) => e.type === 'state_transition');
    const visited = new Set<string>();
    for (const t of transitions) {
      if ('from' in t.data) {
        visited.add(t.data.from);
      }
      if ('to' in t.data) {
        visited.add(t.data.to);
      }
    }
    expect(visited.has('SETUP')).toBe(true);
    expect(visited.has('INTAKE')).toBe(true);
    expect(visited.has('REVIEW_EXECUTION')).toBe(true);
    expect(visited.has('REVIEW_SYNTHESIS')).toBe(true);
    expect(visited.has('DONE')).toBe(true);
  });

  it('sources propagate through config', async () => {
    const artifactStore = createMockArtifactStore();
    const runner = createPrReviewRunner(artifactStore);
    const governance = createMockGovernance();
    const contractRegistry = new DefaultIterationContractRegistry();
    const journalWriter = new DefaultJournalWriter(journalPath, 'run-pr-sources-001');
    const statePersistence = createMockStatePersistence();
    const manifestProducer = createMockManifestProducer();

    const controller = new LifecycleController({
      runner,
      artifactStore,
      governanceEngine: governance,
      contractRegistry,
      journalWriter,
      statePersistence,
      manifestProducer,
    });

    const prUrl = 'https://github.com/org/repo/pull/42';
    const config = {
      runId: 'run-pr-sources-001',
      workflowDefinition: TEST_PR_REVIEW_WORKFLOW,
      governancePolicy: {},
      roleAssignments: {},
      sources: [prUrl],
    };

    await controller.start(config);

    const state = controller.getState();
    expect(state.runId).toBe('run-pr-sources-001');

    // eslint-disable-next-line @typescript-eslint/unbound-method
    expect(statePersistence.save).toHaveBeenCalled();
  });

  it('REVIEW_EXECUTION governance block → FAILED', async () => {
    const artifactStore = createMockArtifactStore();
    const runner = createPrReviewRunner(artifactStore);
    let callCount = 0;

    const governance: GovernanceEngine = {
      evaluateTransition: vi.fn((req: { from: string; to: string }): TransitionDecision => {
        if (req.from === req.to) {
          return { allowed: true, reason: 'pre-dispatch pass' };
        }
        callCount++;
        if (req.from === 'REVIEW_EXECUTION' && callCount <= 3) {
          return { allowed: false, reason: 'governance blocked' };
        }
        return { allowed: true, reason: 'approved' };
      }),
      checkAgreement: vi.fn(() => ({ exists: true, valid: true })),
      recordDecision: vi.fn(),
    };

    const contractRegistry = new DefaultIterationContractRegistry();
    const journalWriter = new DefaultJournalWriter(journalPath, 'run-pr-fail-001');
    const statePersistence = createMockStatePersistence();
    const manifestProducer = createMockManifestProducer();

    const controller = new LifecycleController({
      runner,
      artifactStore,
      governanceEngine: governance,
      contractRegistry,
      journalWriter,
      statePersistence,
      manifestProducer,
    });

    const config = {
      runId: 'run-pr-fail-001',
      workflowDefinition: TEST_PR_REVIEW_WORKFLOW,
      governancePolicy: {},
      roleAssignments: {},
      sources: ['https://github.com/org/repo/pull/99'],
    };

    let result = await controller.start(config);

    let iterations = 0;
    while (
      result.finalState !== 'DONE' &&
      result.finalState !== 'FAILED' &&
      result.finalState !== 'ABORTED' &&
      iterations < 15
    ) {
      result = await controller.resume({ type: 'approval', content: 'Approved' });
      iterations++;
    }

    expect(['DONE', 'FAILED', 'ABORTED']).toContain(result.finalState);
  });
});
